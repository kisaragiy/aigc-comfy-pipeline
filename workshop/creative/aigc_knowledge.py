def suggest_outfit(gender: str = "女", style: str = "甜系", season: str = "春") -> dict:
    """根据性别+风格+季节推荐穿搭"""
    candidates = [g for g in GARMENTS.values()
                  if gender in g.genders
                  and style in g.styles
                  and season in g.seasons]
    
    tops = [g.name for g in candidates if g.category == "上装"]
    bottoms = [g.name for g in candidates if g.category == "下装"]
    outers = [g.name for g in candidates if g.category == "外套"]
    shoes = [g.name for g in candidates if g.category == "鞋"]
    full = [g.name for g in candidates if g.category == "连体"]
    
    return {
        "方案A(连体)": {"衣服": full[:1] if full else [], "鞋子": shoes[:1] if shoes else []},
        "方案B(分体)": {"上装": tops[:1] if tops else [], "下装": bottoms[:1] if bottoms else [],
                       "外套": outers[:1] if outers else [], "鞋子": shoes[:1] if shoes else []},
    }

def suggest_hairstyle(gender: str = "女", vibe: str = "温柔") -> list[str]:
    """根据性别+气质推荐发型"""
    return [name for name, info in HAIRSTYLES.items()
            if gender in info["gender"] and vibe in info["vibe"]]

def suggest_expression(vibe: str = "甜美") -> list[str]:
    """根据情绪推荐表情"""
    return [name for name, info in EXPRESSIONS.items() if vibe in info["vibe"]]

