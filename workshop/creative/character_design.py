def design_character(
    archetype_name: str = "傲娇",
    hair_color: str = "金",
    hair_style: str = "高双马尾",
    eye_type: str = "吊眼角",
    eye_color: str = "蓝瞳",
    costume: str = "西式校服",
    gender: str = "女",
    age_group: str = "高中生",
) -> dict:
    """生成完整的角色设计方案"""
    arch = ARCHETYPES.get(archetype_name, {})
    hair_info = ANIME_HAIRSTYLES.get(hair_style, {})
    hair_color_info = ANIME_HAIR_COLORS.get(hair_color, {})
    eye_info = ANIME_EYE_TYPES.get(eye_type, {})
    costume_info = ANIME_COSTUMES.get(costume, {})
    bg = ANIME_BACKGROUNDS
    
    return {
        "属性": archetype_name,
        "性格特征": getattr(arch, "traits", []),
        "发型": f"{hair_color}色{hair_style}",
        "发质特征": f"{hair_info.get('length','')} {hair_info.get('position','')}",
        "发色氛围": f"{hair_color_info.get('vibe', [])}",
        "眼型": f"{eye_type}({eye_info.get('shape','')})",
        "眼神氛围": f"{eye_info.get('vibe', [])}",
        "瞳色": eye_color,
        "服装": costume,
        "服装设计": getattr(costume_info, "base_design", ""),
        "年龄": age_group,
        "prompt_tags": " ".join([
            f"{hair_color} hair", hair_style, eye_type, eye_color,
            *getattr(costume_info, "prompt_tags", []),
        ])
    }


def character_to_prompt(design: dict) -> str:
    """角色设计 → ComfyUI 提示词"""
    parts = [f"1girl" if design.get("年龄","").startswith("高") else "1girl"]
    parts.append(f"{design.get('发型','')}, {design.get('眼型','')}, {design.get('瞳色','')}")
    parts.append(f"{design.get('服装','')}, {design.get('服装设计','')}")
    parts.append(f"{design.get('属性','')}, {design.get('性格特征','')}")
    parts.append("masterpiece, best quality, ultra detailed")
    return ", ".join(p for p in parts if p)


def galgame_prompt(archetype: str, scene: str = "教室") -> str:
    """Galgame 定番场景提示词生成"""
    arch_info = GALGAME_ARCHETYPES.get(archetype, {})
    bg_info = ANIME_BACKGROUNDS.get(scene, {})
    
    char_tags = " ".join([
        archetype,
        arch_info.get("发型", ""),
        arch_info.get("瞳色", ""),
        arch_info.get("性格", ""),
    ])
    bg_tags = " ".join(bg_info.get("prompt_tags", []))
    
    prompt = f"({archetype}), {char_tags}, {bg_tags}, "
    prompt += "galgame style, anime screencap, visual novel, high quality illustration, masterpiece"
    if scene:
        prompt += f", {bg_info.get('光线','')}"
    
    return prompt


