def analyze_garment_details(category: str, keywords: list[str]) -> dict:
    """分析服装的关键属性组合"""
    # 兼容传入字符串而非列表
    if isinstance(keywords, str):
        keywords = [keywords]
    result = {"category": category, "keywords": keywords, "details": {}}
    
    # 检测是否有丝袜相关描述
    hosiery_matches = []
    for hose_name, hose_spec in HOSIERY_TYPES.items():
        if any(kw in hose_name for kw in keywords):
            hosiery_matches.append({
                "type": hose_spec.type,
                "denier": f"{hose_spec.denier_range[0]}-{hose_spec.denier_range[1]}D",
                "material": hose_spec.materials,
                "opacity": hose_spec.opacity,
                "texture": hose_spec.texture,
            })
    if hosiery_matches:
        result["details"]["stockings"] = hosiery_matches
    
    # 检测鞋子
    shoe_matches = []
    for shoe_name, shoe_spec in SHOES.items():
        if any(kw in shoe_name for kw in keywords + [category]):
            shoe_matches.append({
                "type": shoe_spec.type,
                "heel": f"{shoe_spec.heel_style} ({shoe_spec.heel_height_cm[0]}-{shoe_spec.heel_height_cm[1]}cm)",
                "toe": shoe_spec.toe_style,
                "material": shoe_spec.material,
            })
    if shoe_matches:
        result["details"]["shoes"] = shoe_matches
    
    # 检测面料
    fabric_matches = []
    for fabric_name, fabric_spec in FABRICS.items():
        if any(kw == fabric_name for kw in keywords) or any(kw in fabric_name for kw in keywords):
            fabric_matches.append({
                "composition": fabric_spec["composition"],
                "characteristics": fabric_spec["特性"],
            })
    if fabric_matches:
        result["details"]["fabric"] = fabric_matches
    
    return result


def garment_detail_prompt(garment_list: list[dict]) -> str:
    """把深度服装分类转换成 ComfyUI 提示词可以用的描述"""
    parts = []
    for g in garment_list:
        name = g.get("type", g.get("name", ""))
        if "denier" in g:
            parts.append(f"{name}({g['denier']}, {g['material'][0] if g.get('material') else ''}, {g['texture']})")
        elif "heel" in g:
            parts.append(f"{name}({g['heel']}, {g['toe']})")
        else:
            parts.append(name)
    return ", ".join(parts)


